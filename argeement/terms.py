"""Licence of the published data and the terms of the source databases.

One text, used in three places: LICENSE.md of the export (and so of the Zenodo archive), the Zenodo
description and the web page. The code itself is under the MIT licence (LICENSE in the repository).
"""
import html

DATA_LICENCE = "CC-BY-4.0"
DATA_LICENCE_URL = "https://creativecommons.org/licenses/by/4.0/"

# (database, terms, link to the terms)
SOURCES = [
    ("AMRFinderPlus (NCBI)",
     "United States Government Work, public domain; cite Feldgarden et al. 2021",
     "https://github.com/ncbi/amr/blob/master/LICENSE"),
    ("CARD (McMaster University)",
     "free for non-commercial research at academic, government and non-profit institutions; "
     "commercial organisations need a licence from McMaster University. The Antibiotic Resistance "
     "Ontology (ARO) is under CC-BY 4.0",
     "https://card.mcmaster.ca/about"),
    ("ResFinder, DisinFinder, PointFinder (Center for Genomic Epidemiology, DTU)",
     "Apache License 2.0",
     "https://bitbucket.org/genomicepidemiology/resfinder_db"),
]

CONTENT = (
    "The data contain identifiers and names of the source entries, public sequence accessions, "
    "protein lengths, hashes of the sequences, and the relations, families and counts computed by "
    "ARGeement. Of CARD they contain only ARO accessions and terms (model names, drug classes, "
    "resistance mechanisms), which are part of the CC-BY 4.0 ontology; they contain no CARD "
    "sequences, model descriptions or other CARD material. No sequence of any source database is "
    "included.")

USE = (
    "Whoever uses the source databases themselves (sequences, models, detection software) is bound "
    "by their terms; in particular, commercial use of CARD requires a licence from McMaster "
    "University. This dataset does not grant any right to the source databases.")


def licence_md(release=None):
    rows = "\n".join(f"| {n} | {t} | {u} |" for n, t, u in SOURCES)
    rel = f" (release `{release}`)" if release else ""
    return f"""# Licence

The data generated by ARGeement{rel} are licensed under the Creative Commons Attribution 4.0
International licence ({DATA_LICENCE}, {DATA_LICENCE_URL}). Please cite the ARGeement paper and the
Zenodo record, and the source databases below.

The ARGeement software is under the MIT licence: https://github.com/solymosin/ARGeement

## Source databases and their terms

| Database | Terms | Details |
|---|---|---|
{rows}

{CONTENT}

{USE}
"""


def licence_html():
    li = "".join(f'<li>{html.escape(n)}: {html.escape(t)} (<a href="{html.escape(u)}">terms</a>)</li>'
                 for n, t, u in SOURCES)
    return (f'<p>The data are licensed under <a href="{DATA_LICENCE_URL}">CC-BY 4.0</a>; the '
            f"ARGeement software under the MIT licence. Source databases and their terms:</p>"
            f"<ul>{li}</ul><p>{html.escape(CONTENT)}</p><p>{html.escape(USE)}</p>")
